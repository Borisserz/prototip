CREATE SCHEMA IF NOT EXISTS public;

-- ─── Таблица налоговых начислений ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS tax_data (
    id          SERIAL PRIMARY KEY,
    period      VARCHAR(7)     NOT NULL,   -- 'YYYY-MM'
    region      VARCHAR(100)   NOT NULL,
    tax_type    VARCHAR(100)   NOT NULL,
    accrued     NUMERIC(18, 2) NOT NULL DEFAULT 0,
    paid        NUMERIC(18, 2) NOT NULL DEFAULT 0,
    debt        NUMERIC(18, 2) NOT NULL DEFAULT 0,
    taxpayers   INTEGER        NOT NULL DEFAULT 0,
    penalties   NUMERIC(18, 2) NOT NULL DEFAULT 0
);

COMMENT ON COLUMN tax_data.period     IS 'Отчётный период в формате YYYY-MM';
COMMENT ON COLUMN tax_data.region     IS 'Район/город Гродненской области';
COMMENT ON COLUMN tax_data.tax_type   IS 'Вид налога';
COMMENT ON COLUMN tax_data.accrued    IS 'Начислено к уплате, бел. руб.';
COMMENT ON COLUMN tax_data.paid       IS 'Фактически уплачено, бел. руб.';
COMMENT ON COLUMN tax_data.debt       IS 'Задолженность (accrued - paid), бел. руб.';
COMMENT ON COLUMN tax_data.taxpayers  IS 'Количество налогоплательщиков';
COMMENT ON COLUMN tax_data.penalties  IS 'Штрафы и пени, бел. руб.';

